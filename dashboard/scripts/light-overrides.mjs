// Writes src/light-overrides.css: light-theme replacements for the opacity
// colour classes the dashboard uses (`text-white/50`, `border-gray-faded/30`,
// ...).
//
// The dark theme builds its text hierarchy and its lines from translucent white
// and gray. Tailwind bakes the opacity into the class, so on a light page the
// same classes blend into washed-out grays. In the light theme each class is
// mapped to a fixed level instead (ink-muted, line, pill-green, ...), with the
// same variants, so `enabled:hover:text-white/50` becomes
// `enabled:hover:text-ink-muted`. Tailwind expands the variants itself (@apply).
//
// The rules use :where() for the theme, so they have the same specificity as the
// classes they replace and come after them; the cascade between base and state
// classes (hover, disabled, ...) stays the same as in the dark theme.
//
// Run after adding or changing opacity colour classes:
//   node scripts/light-overrides.mjs           (writes the file)
//   node scripts/light-overrides.mjs --check   (fails if it is out of date)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src/light-overrides.css');
const sourceDirs = ['src', 'pages'];
const extensions = new Set(['.ts', '.tsx', '.js', '.jsx']);

const textLevel = (opacity) =>
  opacity >= 70 ? 'ink-secondary' : opacity >= 50 ? 'ink-muted' : 'ink-faint';

// [property, colour, opacity] -> light colour, or null to keep the class as is
const rules = [
  // text
  [/^text$/, /^white$/, textLevel],
  [/^text$/, /^gray-faded$/, textLevel],
  [/^text$/, /^gray-300$/, textLevel],
  [/^text$/, /^(blue|green|red|yellow)-faded$/, () => 'ink-faint'],
  // lines
  [
    /^(border|border-[trblxy])$/,
    /^gray-faded$/,
    (o) => (o >= 50 ? 'line-strong' : o >= 30 ? 'line' : 'line-subtle'),
  ],
  [/^outline$/, /^gray-faded$/, () => 'line-strong'],
  [/^divide(-[xy])?$/, /^gray-faded$/, () => 'line-subtle'],
  [/^(border|outline)$/, /^fade-700$/, () => 'line-subtle'],
  [
    /^(border|outline)$/,
    /^white$/,
    (o) => (o >= 50 ? 'line-hover' : 'line-strong'),
  ],
  // fills
  [
    /^bg$/,
    /^gray-faded$/,
    (o) => (o >= 40 ? 'fill-neutral-strong' : 'fill-neutral'),
  ],
  [
    /^bg$/,
    /^(green|red|yellow|blue)-faded$/,
    (o, c) =>
      o <= 25
        ? `pill-${c.split('-')[0]}`
        : c === 'blue-faded' && o <= 30
          ? 'fill-selected'
          : null,
  ],
  // focus rings
  [/^ring$/, /^blue-faded$/, (o) => (o >= 50 ? 'focus' : null)],
  [/^ring$/, /^red-faded$/, (o) => (o >= 30 ? 'focus-danger' : null)],
];

const classPattern =
  /(?<![\w-])((?:[\w-]+(?:\[[^\]\s]*\])?:)*)(text|bg|border(?:-[trblxy])?|outline|divide(?:-[xy])?|ring)-((?:white|gray-faded|gray-300|fade-700|(?:blue|green|red|yellow)-faded))\/(\d+)(?![\w/-])/g;

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return extensions.has(path.extname(entry.name)) ? [full] : [];
  });

const found = new Map();
const unmapped = new Set();
for (const file of sourceDirs.flatMap((d) => walk(path.join(root, d)))) {
  const text = fs.readFileSync(file, 'utf8');
  for (const match of text.matchAll(classPattern)) {
    const [className, variants, property, colour, opacityText] = match;
    // already light-only, or written for the dark theme on purpose
    if (/(^|:)(light|dark):/.test(variants)) continue;
    const opacity = Number(opacityText);
    const rule = rules.find(([p, c]) => p.test(property) && c.test(colour));
    const target = rule?.[2](opacity, colour);
    if (!target) {
      unmapped.add(className);
      continue;
    }
    found.set(className, `${variants}${property}-${target}`);
  }
}

// CSS.escape for class names (no leading digit to worry about)
const escape = (name) => name.replace(/[^\w-]/g, (c) => `\\${c}`);

// fewer variants first, like Tailwind orders them, so state classes still win
const variantCount = (name) => name.split(':').length;
const entries = [...found].sort(
  ([a], [b]) => variantCount(a) - variantCount(b) || a.localeCompare(b)
);

const css = `/* Generated by scripts/light-overrides.mjs. Do not edit; run the script.
 *
 * In the light theme, the opacity colour classes map to fixed levels (see the
 * script and the [data-theme='light'] colours in globals.css). The dark theme
 * is unaffected. ${entries.length} classes. */

@layer utilities {
${entries
  .map(
    ([from, to]) =>
      `  :where([data-theme='light']) .${escape(from)} {\n    @apply ${to};\n  }`
  )
  .join('\n')}
}
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== css) {
    console.error(
      'src/light-overrides.css is out of date: run node scripts/light-overrides.mjs'
    );
    process.exit(1);
  }
} else {
  fs.writeFileSync(out, css);
}
console.log(`${entries.length} classes mapped`);
if (unmapped.size)
  console.log(`kept as they are: ${[...unmapped].sort().join(' ')}`);
