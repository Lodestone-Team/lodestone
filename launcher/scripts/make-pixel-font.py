def trimmed(rows):
    """The bitmap without its empty columns on the left and right, so the font is
    proportional: an i is narrower than an m."""
    used = [i for row in rows for i, c in enumerate(row) if c == "#"]
    if not used:
        return rows, 3
    left, right = min(used), max(used)
    return [row[left:right + 1] for row in rows], right - left + 1


def glyph(rows):
    rows, _ = trimmed(rows)
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        top = (7 - r) * PX
        x = 0
        while x < len(row):
            if row[x] != "#":
                x += 1
                continue
            start = x
            while x < len(row) and row[x] == "#":
                x += 1
            left, right = start * PX, x * PX
            pen.moveTo((left, top - PX))
            pen.lineTo((left, top))
            pen.lineTo((right, top))
            pen.lineTo((right, top - PX))
            pen.closePath()
    return pen.glyph()


def main():
    names = {ch: ("space" if ch == " " else f"uni{ord(ch):04X}") for ch in G}
    order = [".notdef"] + [names[ch] for ch in G]
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(ch): names[ch] for ch in G})
    notdef = TTGlyphPen(None)
    for x0, y0, x1, y1 in [(0, 0, 500, 100), (0, 600, 500, 700), (0, 100, 100, 600), (400, 100, 500, 600)]:
        notdef.moveTo((x0, y0)); notdef.lineTo((x0, y1)); notdef.lineTo((x1, y1)); notdef.lineTo((x1, y0)); notdef.closePath()
    glyphs = {".notdef": notdef.glyph()}
    glyphs.update({names[ch]: glyph(rows) for ch, rows in G.items()})
    fb.setupGlyf(glyphs)
    # a narrower space, so words don't drift apart
    # proportional: each glyph's width and a pixel of space; a narrower space
    widths = {names[ch]: (trimmed(rows)[1] + 1) * PX for ch, rows in G.items()}
    widths["space"] = 4 * PX
    widths[".notdef"] = ADVANCE
    fb.setupHorizontalMetrics({name: (widths[name], 0) for name in order})
    fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT)
    fb.setupNameTable({
        "familyName": "Lodestone Pixel",
        "styleName": "Regular",
        "fullName": "Lodestone Pixel Regular",
        "psName": "LodestonePixel-Regular",
        "uniqueFontIdentifier": "LodestonePixel-Regular-1.0",
        "version": "Version 1.000",
        "copyright": "Copyright 2026 The Lodestone Launcher authors",
        "licenseDescription": "This Font Software is licensed under the SIL Open Font License, Version 1.1.",
        "licenseInfoURL": "https://openfontlicense.org",
    })
    fb.setupOS2(sTypoAscender=ASCENT, sTypoDescender=-DESCENT, usWinAscent=ASCENT, usWinDescent=DESCENT,
                sxHeight=5 * PX, sCapHeight=7 * PX, usWeightClass=400)
    fb.setupPost()
    out = os.path.join(os.path.dirname(__file__), "..", "assets", "fonts", "lodestone-pixel", "LodestonePixel-Regular.ttf")
    fb.save(out)
    print("wrote", os.path.normpath(out), len(G), "glyphs")


if __name__ == "__main__":
    main()
