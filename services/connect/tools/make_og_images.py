#!/usr/bin/env python3
"""Renders the OpenGraph cards of the invite and friend link pages.

    python tools/make_og_images.py

Reads og-src/cover.png (the launcher's artwork with the Lodestone logo) and the
launcher's Clash Grotesk font, writes og-src/invite.png and og-src/friend.png
(1200x630, for Discord's large card) and src/og-images.js, which the Worker serves
them from. Needs Pillow. The cards are the same for every code: nothing on them
depends on a server or a friend.
"""
import base64
import io
import pathlib

from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).resolve().parent.parent
FONT = HERE.parent.parent / "launcher" / "assets" / "fonts" / "clash-grotesk" / "ClashGrotesk-Bold.otf"
FONT_MEDIUM = FONT.with_name("ClashGrotesk-Medium.otf")
W, H = 1200, 630

CARDS = {
    "invite": ("Join my\nMinecraft server", "Open this link in Lodestone Launcher"),
    "friend": ("Let's be friends\non Lodestone", "Open this link in Lodestone Launcher"),
}


def background():
    art = Image.open(HERE / "og-src" / "cover.png").convert("RGB")
    scale = W / art.width
    art = art.resize((W, round(art.height * scale)), Image.LANCZOS)
    top = (art.height - H) // 2
    art = art.crop((0, top, W, top + H))
    # A shade from the left, so the text reads over the dark side of the artwork.
    shade = Image.new("L", (W, H))
    px = shade.load()
    for x in range(W):
        a = max(0.0, 1.0 - x / 900) ** 1.1 * 0.9
        for y in range(H):
            # ...and fades out toward the bottom, where the logo is.
            fade = min(1.0, max(0.0, (520 - y) / 110))
            px[x, y] = round(255 * a * fade)
    return Image.composite(Image.new("RGB", (W, H), (14, 15, 20)), art, shade)


def render(title, subtitle):
    image = background()
    draw = ImageDraw.Draw(image)
    big = ImageFont.truetype(str(FONT), 70)
    small = ImageFont.truetype(str(FONT_MEDIUM), 30)
    y = 70
    for line in title.split("\n"):
        draw.text((64, y), line, font=big, fill=(240, 240, 238))
        y += 84
    draw.text((66, y + 18), subtitle, font=small, fill=(176, 184, 196))
    return image


def main():
    modules = []
    for name, (title, subtitle) in CARDS.items():
        image = render(title, subtitle)
        # A palette keeps the file small: the Worker carries it as text.
        image = image.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.FLOYDSTEINBERG)
        buffer = io.BytesIO()
        image.save(buffer, "PNG", optimize=True)
        data = buffer.getvalue()
        (HERE / "og-src" / f"{name}.png").write_bytes(data)
        print(name, len(data), "bytes")
        modules.append(f"  {name}: '{base64.b64encode(data).decode()}',")
    (HERE / "src" / "og-images.js").write_text(
        "// The link pages' OpenGraph cards (1200x630 PNGs, base64). Generated by\n"
        "// tools/make_og_images.py from og-src/: don't edit by hand.\n"
        "export const OG_IMAGES = {\n" + "\n".join(modules) + "\n};\n",
        newline="\n",
    )


main()
