//! Mojang's Minecraft EULA. A Minecraft server only runs when its `eula.txt` says
//! `eula=true`. Only the user can agree to the EULA, so Lodestone writes `eula=true` only
//! when the user asked for it: when they create an instance with `accept_eula`, or with
//! `PUT /instance/{uuid}/eula`.

use std::path::Path;

use color_eyre::eyre::{eyre, Context};
use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::error::{Error, ErrorKind};

/// Where users read the Minecraft EULA.
pub const EULA_URL: &str = "https://aka.ms/MinecraftEULA";

/// The EULA file in a Minecraft instance folder.
pub const EULA_FILE: &str = "eula.txt";

/// Whether the user has accepted the Minecraft EULA for an instance.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, TS, PartialEq, Eq)]
#[ts(export)]
pub struct EulaStatus {
    pub accepted: bool,
}

/// The content Lodestone writes to `eula.txt`.
pub fn eula_file_content(accepted: bool) -> String {
    format!("#generated by Lodestone\neula={accepted}")
}

/// Whether the content of an `eula.txt` accepts the EULA. Like Minecraft, this reads
/// the file as Java properties and looks for `eula` set to `true` (in any case).
pub fn eula_text_accepts(content: &str) -> bool {
    let mut accepted = false;
    for line in content.lines() {
        let line = line.trim_start();
        if line.is_empty() || line.starts_with('#') || line.starts_with('!') {
            continue;
        }
        let Some(split) = line.find(['=', ':']) else {
            continue;
        };
        let (key, value) = (&line[..split], &line[split + 1..]);
        if key.trim() == "eula" {
            // a later line wins, as in a properties file
            accepted = value.trim().eq_ignore_ascii_case("true");
        }
    }
    accepted
}

/// Whether the instance in `instance_dir` has the EULA accepted. A missing `eula.txt`
/// means it is not.
pub async fn is_eula_accepted(instance_dir: &Path) -> Result<bool, Error> {
    match tokio::fs::read_to_string(instance_dir.join(EULA_FILE)).await {
        Ok(content) => Ok(eula_text_accepts(&content)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(e) => Err(Error::from(
            eyre!(e).wrap_err("Could not read the server's eula.txt"),
        )),
    }
}

/// The error for starting a server whose EULA is not accepted.
pub fn eula_not_accepted_error() -> Error {
    Error {
        kind: ErrorKind::BadRequest,
        source: eyre!(
            "Accept the Minecraft EULA ({EULA_URL}) before you start this server. A Minecraft server only runs after you agree to it."
        ),
    }
}

/// Returns an error unless the instance in `instance_dir` has the EULA accepted.
/// Starting a server calls this first.
pub async fn require_eula_accepted(instance_dir: &Path) -> Result<(), Error> {
    if is_eula_accepted(instance_dir).await? {
        Ok(())
    } else {
        Err(eula_not_accepted_error())
    }
}

/// Writes `eula.txt` for the instance in `instance_dir`. Only call this with `true`
/// when the user agreed to the EULA.
pub async fn write_eula(instance_dir: &Path, accepted: bool) -> Result<(), Error> {
    tokio::fs::write(instance_dir.join(EULA_FILE), eula_file_content(accepted))
        .await
        .context("Could not write the server's eula.txt")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::implementations::minecraft::{Flavour, MinecraftInstance, SetupConfig};
    use crate::traits::t_configurable::manifest::SetupValue;

    fn setup_config(accept_eula: bool) -> SetupConfig {
        SetupConfig {
            name: "Survival".to_string(),
            version: "1.21.1".to_string(),
            flavour: Flavour::Vanilla,
            port: 25565,
            existing_server_path: None,
            import_scripts: false,
            cmd_args: Vec::new(),
            description: None,
            min_ram: None,
            max_ram: None,
            auto_start: None,
            restart_on_crash: None,
            backup_period: None,
            modpack: None,
            accept_eula,
        }
    }

    #[test]
    fn reads_eula_files_like_minecraft() {
        for accepted in [
            "#generated by Lodestone\neula=true",
            "eula=TRUE\n",
            "#By changing the setting below to TRUE...\n#Mon Jan 01\neula = true \n",
            "eula:true",
            "eula=false\neula=true",
        ] {
            assert!(eula_text_accepts(accepted), "{accepted:?}");
        }
        for refused in [
            "",
            "#generated by Lodestone\neula=false",
            "#eula=true",
            "! eula=true",
            "eula=yes",
            "eula=true\neula=false",
            "not_eula=true",
            "eula",
        ] {
            assert!(!eula_text_accepts(refused), "{refused:?}");
        }
        assert!(eula_text_accepts(&eula_file_content(true)));
        assert!(!eula_text_accepts(&eula_file_content(false)));
    }

    #[tokio::test]
    async fn starting_needs_the_eula_accepted() {
        let dir = tempfile::tempdir().unwrap();
        // no eula.txt at all
        assert!(!is_eula_accepted(dir.path()).await.unwrap());
        let error = require_eula_accepted(dir.path()).await.unwrap_err();
        assert!(matches!(error.kind, ErrorKind::BadRequest));
        let message = error.source.to_string();
        assert!(message.contains("Accept the Minecraft EULA"), "{message}");
        assert!(message.contains(EULA_URL), "{message}");

        write_eula(dir.path(), false).await.unwrap();
        assert!(require_eula_accepted(dir.path()).await.is_err());

        write_eula(dir.path(), true).await.unwrap();
        require_eula_accepted(dir.path()).await.unwrap();
        assert_eq!(
            std::fs::read_to_string(dir.path().join(EULA_FILE)).unwrap(),
            "#generated by Lodestone\neula=true"
        );
    }

    #[tokio::test]
    async fn new_instances_have_the_eula_accepted_only_when_asked() {
        let dir = tempfile::tempdir().unwrap();
        let refused = dir.path().join("refused");
        MinecraftInstance::create_instance_files(&refused, &setup_config(false))
            .await
            .unwrap();
        assert_eq!(
            std::fs::read_to_string(refused.join(EULA_FILE)).unwrap(),
            "#generated by Lodestone\neula=false"
        );
        assert!(require_eula_accepted(&refused).await.is_err());

        let accepted = dir.path().join("accepted");
        MinecraftInstance::create_instance_files(&accepted, &setup_config(true))
            .await
            .unwrap();
        assert_eq!(
            std::fs::read_to_string(accepted.join(EULA_FILE)).unwrap(),
            "#generated by Lodestone\neula=true"
        );
        require_eula_accepted(&accepted).await.unwrap();
        assert_eq!(
            std::fs::read_to_string(accepted.join("server.properties")).unwrap(),
            "server-port=25565\n"
        );
    }

    #[test]
    fn create_requests_leave_the_eula_unaccepted_by_default() {
        let setup_value = |extra: serde_json::Value| -> SetupValue {
            let mut value = serde_json::json!({
                "name": "Survival",
                "description": null,
                "auto_start": false,
                "restart_on_crash": false,
                "setting_sections": {},
            });
            value
                .as_object_mut()
                .unwrap()
                .extend(extra.as_object().unwrap().clone());
            serde_json::from_value(value).unwrap()
        };
        assert!(!setup_value(serde_json::json!({})).accept_eula);
        assert!(setup_value(serde_json::json!({ "accept_eula": true })).accept_eula);

        let request: crate::handlers::modpack::CreateModpackInstanceRequest =
            serde_json::from_value(serde_json::json!({
                "source": { "type": "upload", "upload_id": "abc" },
                "name": "Pack",
                "port": 25565,
            }))
            .unwrap();
        assert!(!request.accept_eula);
    }
}
