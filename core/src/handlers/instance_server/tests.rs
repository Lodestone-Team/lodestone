//! The Minecraft EULA endpoints, against a core on a loopback port with a real (never
//! started) Minecraft instance restored from files in a temporary folder.

use std::collections::HashSet;

use reqwest::{Method, StatusCode};
use serde_json::{json, Value};

use super::*;
use crate::{
    auth::{permission::UserPermission, user::User},
    events::CausedBy,
    global_settings::{CodeExecutionSwitch, GlobalSettingsData},
    implementations::minecraft::eula::EULA_URL,
    macro_executor::MacroExecutor,
    test_util::{serve_api, test_app_state},
    types::DotLodestoneConfig,
};

fn init_paths() {
    static LODESTONE_DIR: std::sync::OnceLock<tempfile::TempDir> = std::sync::OnceLock::new();
    let dir = LODESTONE_DIR.get_or_init(|| tempfile::tempdir().unwrap());
    crate::prelude::try_init_paths(dir.path().to_owned()).unwrap();
}

struct Core {
    _dir: tempfile::TempDir,
    state: AppState,
    root: std::path::PathBuf,
    base: String,
    client: reqwest::Client,
    uuid: InstanceUuid,
}

/// A core with one vanilla instance whose folder has no `eula.txt`, as a new instance
/// created without `accept_eula` has `eula=false`.
async fn core() -> Core {
    init_paths();
    let dir = tempfile::tempdir().unwrap();
    let state = test_app_state(
        dir.path(),
        GlobalSettingsData {
            code_execution_enabled: false,
            safe_mode: false,
            ..Default::default()
        },
    )
    .await;
    let instances = dir.path().join("instances");
    let root = instances.join("vanilla");
    std::fs::create_dir_all(&root).unwrap();
    let uuid = InstanceUuid::default();
    std::fs::write(
        root.join(".lodestone_config"),
        serde_json::to_string(&DotLodestoneConfig::new(
            uuid.clone(),
            crate::traits::t_configurable::GameType::MinecraftJava,
        ))
        .unwrap(),
    )
    .unwrap();
    std::fs::write(
        root.join(".lodestone_minecraft_config.json"),
        json!({
            "name": "Survival", "version": "1.21.1", "flavour": "vanilla",
            "description": "", "cmd_args": [], "java_cmd": "java",
            "port": 25571, "min_ram": 1024, "max_ram": 2048, "auto_start": false,
            "restart_on_crash": false, "backup_period": null, "jre_major_version": 21,
            "has_started": false
        })
        .to_string(),
    )
    .unwrap();
    std::fs::write(root.join("server.properties"), "server-port=25571\n").unwrap();
    std::fs::write(root.join("eula.txt"), "#generated by Lodestone\neula=false").unwrap();
    let executor = MacroExecutor::new(
        state.event_broadcaster.clone(),
        tokio::runtime::Handle::current(),
        CodeExecutionSwitch::new(false),
    );
    let restored = crate::restore_instances(
        &instances,
        &state.instance_folders,
        state.event_broadcaster.clone(),
        executor,
    )
    .await
    .unwrap();
    for (uuid, instance) in crate::snapshot_instances(&restored) {
        state.instances.insert(uuid, instance);
    }
    assert_eq!(state.instances.len(), 1);
    let base = serve_api(state.clone()).await;
    Core {
        _dir: dir,
        state,
        root,
        base,
        client: reqwest::Client::new(),
        uuid,
    }
}

impl Core {
    async fn user(&self, name: &str, is_owner: bool, permissions: UserPermission) -> String {
        let user = User::new(name.to_string(), "pw", is_owner, false, permissions);
        self.state
            .users_manager
            .write()
            .await
            .add_user(user.clone(), CausedBy::System)
            .await
            .unwrap();
        user.create_jwt().unwrap().to_string()
    }

    async fn call(&self, method: Method, token: &str) -> (StatusCode, Value) {
        let response = self
            .client
            .request(method, format!("{}/instance/{}/eula", self.base, self.uuid))
            .bearer_auth(token)
            .send()
            .await
            .unwrap();
        let status = response.status();
        let text = response.text().await.unwrap();
        (
            status,
            serde_json::from_str(&text).unwrap_or(Value::String(text)),
        )
    }

    fn eula_file(&self) -> String {
        std::fs::read_to_string(self.root.join("eula.txt")).unwrap()
    }
}

#[tokio::test]
async fn the_eula_is_accepted_only_by_users_who_may_start_the_server() {
    let core = core().await;
    let owner = core.user("owner", true, Default::default()).await;
    let viewer = core
        .user(
            "viewer",
            false,
            UserPermission {
                can_view_instance: HashSet::from([core.uuid.clone()]),
                ..Default::default()
            },
        )
        .await;
    let starter = core
        .user(
            "starter",
            false,
            UserPermission {
                can_view_instance: HashSet::from([core.uuid.clone()]),
                can_start_instance: HashSet::from([core.uuid.clone()]),
                ..Default::default()
            },
        )
        .await;
    let stranger = core.user("stranger", false, Default::default()).await;

    // a new server without `accept_eula` can't start
    assert_eq!(
        core.call(Method::GET, &owner).await,
        (StatusCode::OK, json!({ "accepted": false }))
    );
    assert_eq!(
        core.call(Method::GET, &viewer).await,
        (StatusCode::OK, json!({ "accepted": false }))
    );
    let minecraft = minecraft_instance(&core.state, &core.uuid).unwrap();
    assert!(!minecraft.eula_accepted().await.unwrap());
    let error = crate::implementations::minecraft::eula::require_eula_accepted(&core.root)
        .await
        .unwrap_err();
    assert!(error.source.to_string().contains(EULA_URL));

    // viewing is not enough to accept it, and others can't even look
    let (status, _) = core.call(Method::PUT, &viewer).await;
    assert_eq!(status, StatusCode::FORBIDDEN);
    let (status, _) = core.call(Method::GET, &stranger).await;
    assert_eq!(status, StatusCode::FORBIDDEN);
    let (status, _) = core.call(Method::PUT, &stranger).await;
    assert_eq!(status, StatusCode::FORBIDDEN);
    assert_eq!(core.eula_file(), "#generated by Lodestone\neula=false");

    // a user who may start the server accepts it
    assert_eq!(
        core.call(Method::PUT, &starter).await,
        (StatusCode::OK, json!({ "accepted": true }))
    );
    assert_eq!(core.eula_file(), "#generated by Lodestone\neula=true");
    assert_eq!(
        core.call(Method::GET, &owner).await,
        (StatusCode::OK, json!({ "accepted": true }))
    );
    assert!(minecraft.eula_accepted().await.unwrap());
    crate::implementations::minecraft::eula::require_eula_accepted(&core.root)
        .await
        .unwrap();
}

#[tokio::test]
async fn the_eula_of_a_missing_server_is_not_found() {
    let core = core().await;
    let owner = core.user("owner", true, Default::default()).await;
    let response = core
        .client
        .put(format!(
            "{}/instance/{}/eula",
            core.base,
            InstanceUuid::default()
        ))
        .bearer_auth(&owner)
        .send()
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::NOT_FOUND);
}
